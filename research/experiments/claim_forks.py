ROOT = Path(__file__).resolve().parents[2]
GATE = runpy.run_path(str(Path(__file__).with_name("claim_gate.py")))
DATA = GATE["DATA"]
sha, write_json = GATE["sha"], GATE["write_json"]


def predicate_boundary(text, entities):
    match = re.fullmatch(
        r"(?:It is (?:not )?established that )?([A-Z][a-z]+) is(?: not)?",
        " ".join(text.split()),
    )
    return match is not None and match[1] in entities


def grade_claim(case, text):
    normalized = " ".join(text.split())
    positive = "It is established that "
    if normalized.lower().startswith(positive.lower()):
        normalized = normalized[len(positive) :]
    return DATA["grade_claim"](case, normalized)


def analyze(rows, *, planned):
    result = GATE["analyze"](rows, planned=planned)
    result["checkpoint_coverage"] = sum(bool(r.get("checkpoint")) for r in rows) / planned
    result["gates"]["checkpoint_coverage"] = result["checkpoint_coverage"] >= 0.8
    result["admitted"] = all(result["gates"].values())
    return result


def source_hashes():
    hashes = GATE["source_hashes"]()
    for name in ("claim_forks.py", "logit_runtime.py"):
        path = Path(__file__).with_name(name)
        hashes[str(path.relative_to(ROOT))] = sha(path)
    return hashes


def prepare(output):
    output.mkdir(parents=True, exist_ok=False)
    original = ROOT / "research/protocols/local-claims-v1"
    manifest = json.loads((original / "manifest.json").read_text())
    for split in ("development", "gate"):
        (output / f"{split}.json").write_bytes((original / f"{split}.json").read_bytes())
    manifest.update(
        schema="claim-forks-v2",
        created_at=datetime.now(UTC).isoformat(),
        source_revision=subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True
        ).strip(),
        source_hashes=source_hashes(),
        candidates=4,
        prefix_tokens=32,
        chunk_tokens=32,
        seconds_per_world=90,
        seconds_per_lookahead=15,
        seed_base=872191,
        prefix_seed_stride=64,
        proposal_policy="Native prefix until first predicate boundary; top-four distinct next "
        "tokens; greedy continuation per branch. Forced root tokens counted separately.",
        revision_reason="V1 development had only 2 mixed batches and missed the exact positive "
        "established wrapper. Same worlds; gate outcomes not collected before V2 freeze.",
        comparator="Mean branch log probability including native probability of forced root; "
        "common prefix excluded. This is a length-normalized search heuristic, "
        "not native sampling.",
    )
    manifest["gates"]["min_checkpoint_coverage"] = 0.8
    write_json(output / "manifest.json", manifest)


def propose(case, request, base, runtime, manifest, seed, *, record=None):
    prompt = base.encode(request)
    opening = base.encode_control("<step>")
    prefix = opening
    trace = []
    if record is None:
        record = {}
    record.update(
        checkpoint=False,
        prompt_token_ids=prompt,
        opening_token_ids=opening,
        prefix_token_ids=prefix,
        prefix_trace=trace,
        candidates=[],
        proposals=[],
    )
    started = time.monotonic()
    checkpoint = None
    # Prefix text is generated by Granite. Entity names only locate a grammar boundary.
    for position in range(manifest["prefix_tokens"] + 1):
        if time.monotonic() - started >= manifest["seconds_per_world"]:
            raise TimeoutError("Native prefix exhausted world time")
        body = base.decode(prefix[len(opening) :])
        state = runtime.inspect(prompt, prefix, count=manifest["candidates"])
        step = {
            "prefix_digest": state.prefix_digest,
            "prefill_tokens": state.prefill_tokens,
            "seconds": state.seconds,
        }
        if predicate_boundary(body, case["entities"]):
            checkpoint = state
            step["checkpoint"] = True
            trace.append(step)
            break
        if position == manifest["prefix_tokens"]:
            step["prefix_limit"] = True
            trace.append(step)
            break
        sample_seed = seed + position
        token, probability, _ = runtime.sample(state, {}, seed=sample_seed)
        trace.append({**step, "token": token, "probability": probability, "seed": sample_seed})
        prefix += (token,)
        record["prefix_token_ids"] = prefix
        if token in base.eos_ids or "</step>" in base.decode(prefix):
            break
    record.update(
        {
            "checkpoint": checkpoint is not None,
            "prompt_token_ids": prompt,
            "opening_token_ids": opening,
            "prefix_token_ids": prefix,
            "prefix_text": base.decode(prefix),
            "prefix_trace": trace,
            "candidates": [],
            "proposals": [],
        }
    )
    if checkpoint is None:
        return record
    record["root_options"] = checkpoint.options
    for token, probability in checkpoint.options:
        remaining = manifest["seconds_per_world"] - (time.monotonic() - started)
        if remaining <= 0:
            raise TimeoutError("Lookaheads exhausted world time")
        branch = runtime.lookahead(
            prompt,
            prefix,
            first_token=token,
            max_tokens=manifest["chunk_tokens"],
            seed=seed,
            max_seconds=min(remaining, manifest["seconds_per_lookahead"]),
        )
        record["proposals"].append(branch)
        ids = branch["token_ids"]
        text = base.decode(prefix + ids)
        frame = parse_frame(text)
        record["candidates"].append(
            {
                "token_ids": ids,
                "text": text,
                "mean_logprob": (
                    math.log(probability) + branch["rest_mean_logprob"] * (len(ids) - 1)
                )
                / len(ids),
                "finish_reason": branch["finish_reason"],
                "body": frame.body if frame and frame.kind == "step" else None,
                "oracle": None,
                "judgment": None,
                "duplicate_of": None,
            }
        )
    return record


async def run(args):
    manifest = json.loads((args.manifest / "manifest.json").read_text())
    if manifest["source_hashes"] != source_hashes():
        raise ValueError("Frozen source changed")
    data_path = args.manifest / f"{args.split}.json"
    if sha(data_path) != manifest["dataset_hashes"][args.split]:
        raise ValueError("Frozen data changed")
    cases = json.loads(data_path.read_text())
    args.output.mkdir(parents=True, exist_ok=False)
    from jev_guided_decoding.backends.transformers import TransformersBackend

    runtime_class = runpy.run_path(str(Path(__file__).with_name("logit_runtime.py")))[
        "LogitTokenBackend"
    ]
    loaded = time.monotonic()
    base = TransformersBackend.load(
        manifest["model"],
        revision=manifest["revision"],
        device=args.device,
        temperature=1.0,
        top_p=1.0,
        local_files_only=args.local_files_only,
    )
    loading_seconds = time.monotonic() - loaded
    runtime = runtime_class(base)
    warm = Request("Write a short claim.", "Rumi is blue.", DATA["CLAIM_SYSTEM"])
    runtime.inspect(base.encode(warm), base.encode_control("<step>"))
    write_json(
        args.output / "metadata.json",
        {
            "manifest_sha256": sha(args.manifest / "manifest.json"),
            "source_hashes": source_hashes(),
            "model": base.metadata(),
            "split": args.split,
            "loading_seconds": loading_seconds,
            "started_at": datetime.now(UTC).isoformat(),
            "planned": len(cases),
            "git_status": subprocess.check_output(
                ["git", "status", "--porcelain"], cwd=ROOT, text=True
            ),
        },
    )
    rows, started = [], time.monotonic()
    with InputTokenBudget(args.ledger, max_usd=3) as budget:
        async with LocalClaimScorer(load_api_key(), budget=budget) as scorer:
            with (args.output / "runs.jsonl").open("x") as stream:
                for case in cases:
                    if time.monotonic() - started >= manifest["stage_seconds"]:
                        break
                    seed = manifest["seed_base"] + case["index"] * manifest["prefix_seed_stride"]
                    request = Request(
                        DATA["request_question"](case), case["evidence"], DATA["CLAIM_SYSTEM"]
                    )
                    record = {
                        "id": case["id"],
                        "motif": case["motif"],
                        "case": case,
                        "status": "started",
                        "seed": seed,
                        "request": asdict(request),
                        "checkpoint": False,
                        "candidates": [],
                    }
                    job_started = time.monotonic()
                    try:
                        propose(case, request, base, runtime, manifest, seed, record=record)
                        valid, indices = [], []
                        for index, candidate in enumerate(record["candidates"]):
                            if (
                                candidate["body"] is not None
                                and candidate["finish_reason"] == "frame"
                            ):
                                valid.append(
                                    Candidate(
                                        tuple(candidate["token_ids"]),
                                        candidate["body"],
                                        candidate["mean_logprob"],
                                        candidate["finish_reason"],
                                    )
                                )
                                indices.append(index)
                        if valid:
                            record["payload"] = scorer._build_payload(request, "", tuple(valid))
                            evaluation = await scorer.score(request, "", tuple(valid), timeout=30)
                            record["evaluation"] = asdict(evaluation)
                            for index, judgment in zip(indices, evaluation.judgments, strict=True):
                                record["candidates"][index]["judgment"] = asdict(judgment)
                        # Independent oracle is absent from the request and all selector inputs.
                        for candidate in record["candidates"]:
                            if candidate["body"] is not None:
                                candidate["oracle"] = grade_claim(case, candidate["body"])
                        record["status"] = "complete"
                    except ScorerError as exc:
                        record.update(
                            status="scorer_error",
                            error=str(exc),
                            usage_unknown=exc.usage_unknown,
                            attempts=exc.attempts,
                        )
                    except Exception as exc:
                        record.update(
                            status="backend_error",
                            error_type=type(exc).__name__,
                            failed_operation_compute_unknown=True,
                        )
                    record["seconds"] = time.monotonic() - job_started
                    stream.write(json.dumps(record, allow_nan=False) + "\n")
                    stream.flush()
                    os.fsync(stream.fileno())
                    rows.append(record)
                    print(
                        json.dumps(
                            {"done": len(rows), "planned": len(cases), "status": record["status"]}
                        ),
                        flush=True,
                    )
                    if record["status"] != "complete":
                        break
        summary = analyze(rows, planned=len(cases))
        summary["ledger_charged_tokens_including_previous_studies"] = budget.charged_tokens
        summary["unsettled_reservations"] = len(set(budget.reserved) - set(budget.settled))
    summary["runs_sha256"] = sha(args.output / "runs.jsonl")
    summary["seconds"] = time.monotonic() - started
    write_json(args.output / "summary.json", summary)
    print(json.dumps(summary, indent=2), flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    p = commands.add_parser("prepare")
    p.add_argument("--output", type=Path, required=True)
    p = commands.add_parser("run")
    p.add_argument("--manifest", type=Path, required=True)
    p.add_argument("--split", choices=["development", "gate"], required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--ledger", type=Path, required=True)
    p.add_argument("--device", default="auto")
    p.add_argument("--local-files-only", action="store_true")
    args = parser.parse_args()
    if args.command == "prepare":
        prepare(args.output)
    else:
        asyncio.run(run(args))


if __name__ == "__main__":
    main()
